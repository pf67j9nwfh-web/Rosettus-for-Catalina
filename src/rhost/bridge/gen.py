#!/usr/bin/python
# gen.py SPEC OUTDIR: generate the hostcall bridge from a signature list.
#   OUTDIR/r2native_gen.c  - i386 stubs (built on Snow Leopard into libr2native.dylib): each packs its
#                            arguments into a block of words and traps into the host (r2_hostcall)
#   OUTDIR/hostcall_gen.c  - host side (built into rhost): unpacks, converts and calls the real
#                            64-bit function of this Mac's frameworks
# Spec lines:  NAME RET ARG ARG ...      (ARG list may be "-" for none)
# Types (i386 view -> host):
#   i int  u unsigned  b Boolean (char)  us unsigned short  q 64-bit int  L long  UL unsigned long
#   f float  g CGFloat (float -> double)  d double  p pointer (same address on both sides)  s C string
#   h native object (handle on the i386 side)  h! the same, released by this call (handle freed)
#   c CF property list object (copied across as a binary plist)
#   R P S A  CGRect / CGPoint / CGSize / CGAffineTransform by value (CGFloats)
#   N  pointer the host cannot use (i386 callback, allocator): passed as NULL
#   pu u32* (as is)  pg CGFloat*  pP CGPoint*  pR CGRect*  pH handle* (out)  pUL unsigned long*
#   H  a handle given as its number (the host function gets the u32: r2h_* helpers)
#   I  pointer-sized opaque ID (PasteboardItemID): small values as is, others through an ID table
#   pI ID* (in/out)  pC CFTypeRef* (out, a +1 object copied back as a property list)
# h! releases: the handle is reference counted (r2_retain); the host function runs on the last release.
# A line "@NAME" exports a CF constant NAME from libr2native (read from the host at load time).
# Returns: v i u b us q L UL g d h C (CF object, +1) P R S
#   W  CFArray of plain 32-bit values (window IDs: CGWindowListCreate), +1, NULL callbacks
import sys, os
CONSTS = []

CTYPE32 = {'i': 'int', 'u': 'unsigned int', 'b': 'unsigned char', 'us': 'unsigned short', 'q': 'long long',
           'L': 'long', 'UL': 'unsigned long', 'f': 'float', 'g': 'float', 'd': 'double', 'p': 'void *',
           's': 'const char *', 'h': 'void *', 'h!': 'void *', 'c': 'CFTypeRef', 'C': 'CFTypeRef', 'W': 'CFArrayRef',
           'R': 'r2_rect32', 'P': 'r2_pt32', 'S': 'r2_size32', 'A': 'r2_aff32', 'pu': 'unsigned int *',
           'pg': 'float *', 'pP': 'r2_pt32 *', 'pR': 'r2_rect32 *', 'pH': 'void **', 'pUL': 'unsigned long *',
           'v': 'void', 'N': 'void *', 'H': 'void *', 'I': 'void *', 'pI': 'void **', 'pC': 'CFTypeRef *'}
NWORDS = {'q': 2, 'd': 2, 'R': 4, 'P': 2, 'S': 2, 'A': 6, 'c': 2, 'pC': 2}

def parse(spec):
    out = []
    for line in open(spec):
        line = line.split('#')[0].strip()
        if not line: continue
        if line.startswith('@'): CONSTS.append(line[1:].strip()); continue
        t = line.split()
        name, ret, args = t[0], t[1], [a for a in t[2:] if a != '-']
        for a in args + [ret]:
            assert a in CTYPE32, (name, a)
        out.append((name, ret, args))   # NAME may be i386name=hostname
    return out

def gen_i386(fns, path):
    o = ['/* generated by gen.py: i386 stubs of the hostcall bridge */',
         '#include "r2native.h"', '']
    for idx, (name, ret, args) in enumerate(fns):
        name = name.split('=')[0]
        params = ', '.join('%s a%d' % (CTYPE32[a], i) for i, a in enumerate(args)) or 'void'
        o.append('%s %s(%s) {' % (CTYPE32[ret], name, params))
        nw = 2 + sum(NWORDS.get(a, 1) for a in args)
        o.append('    unsigned int b[%d]; int k = 2; (void)k;' % max(nw, 6))
        post = []; pos = 2
        for i, a in enumerate(args):
            v = 'a%d' % i
            if a in ('i', 'u', 'b', 'us', 'L', 'UL'): o.append('    b[k++] = (unsigned int)%s;' % v)
            elif a in ('p', 's', 'h', 'h!', 'pu', 'pg', 'pP', 'pR', 'pH', 'pUL', 'N', 'H', 'I', 'pI'): o.append('    b[k++] = (unsigned int)%s;' % v)
            elif a == 'pC':
                o.append('    b[k] = b[k + 1] = 0; k += 2;')
                post.append('    if (%s) *%s = r2_cf_in(b[%d], b[%d]);' % (v, v, pos, pos + 1))
            elif a in ('f', 'g'): o.append('    memcpy(&b[k++], &%s, 4);' % v)
            elif a in ('q', 'd'): o.append('    memcpy(&b[k], &%s, 8); k += 2;' % v)
            elif a in ('R', 'P', 'S', 'A'): o.append('    memcpy(&b[k], &%s, %d); k += %d;' % (v, NWORDS[a] * 4, NWORDS[a]))
            elif a == 'c':
                o.append('    CFDataRef d%d = r2_cf_out(%s); b[k++] = d%d ? (unsigned int)CFDataGetBytePtr(d%d) : 0; b[k++] = d%d ? (unsigned int)CFDataGetLength(d%d) : 0;' % (i, v, i, i, i, i))
                post.append('    if (d%d) CFRelease(d%d);' % (i, i))
            pos += NWORDS.get(a, 1)
        o.append('    r2_hostcall(%d, b);' % idx)
        o.extend(post)
        if ret == 'v': pass
        elif ret in ('i', 'u', 'b', 'us', 'L', 'UL', 'h'): o.append('    return (%s)b[0];' % CTYPE32[ret])
        elif ret in ('q', 'd'): o.append('    { %s r; memcpy(&r, b, 8); return r; }' % CTYPE32[ret])
        elif ret == 'g': o.append('    { float r; memcpy(&r, b, 4); return r; }')
        elif ret in ('P', 'S', 'R'): o.append('    { %s r; memcpy(&r, b + 2, sizeof r); return r; }' % CTYPE32[ret])
        elif ret == 'C': o.append('    return r2_cf_in(b[0], b[1]);')
        elif ret == 'W': o.append('    return r2_ids_in(b[0], b[1]);')
        o.append('}')
        o.append('')
    for c in CONSTS: o.append('CFTypeRef %s;' % c)
    o.append('__attribute__((constructor)) static void r2_consts(void) {')
    o.append('    if (!r2_available()) return;')
    for c in CONSTS: o.append('    %s = r2_cfconst("%s");' % (c, c))
    o.append('}')
    open(path, 'w').write('\n'.join(o) + '\n')

HTYPE = {'i': 'int', 'u': 'unsigned int', 'b': 'unsigned char', 'us': 'unsigned short', 'q': 'long long',
         'L': 'long', 'UL': 'unsigned long', 'f': 'float', 'g': 'CGFloat', 'd': 'double', 'p': 'void *',
         's': 'const char *', 'h': 'void *', 'h!': 'void *', 'c': 'CFTypeRef', 'C': 'CFTypeRef', 'W': 'CFArrayRef',
         'R': 'CGRect', 'P': 'CGPoint', 'S': 'CGSize', 'A': 'CGAffineTransform', 'pu': 'unsigned int *',
         'pg': 'CGFloat *', 'pP': 'CGPoint *', 'pR': 'CGRect *', 'pH': 'void **', 'pUL': 'unsigned long *',
         'v': 'void', 'N': 'void *', 'H': 'u32', 'I': 'void *', 'pI': 'void **', 'pC': 'CFTypeRef *'}

def gen_host(fns, path):
    o = ['/* generated by gen.py: host side of the hostcall bridge */',
         '#include "hostcall.h"', '']
    for idx, (name, ret, args) in enumerate(fns):
        hname = name.split('=')[-1]; name = name.split('=')[0]
        o.append('static void hc_%s(u32 *b) {' % name)
        o.append('    static %s (*f)(%s);' % (HTYPE[ret], ', '.join(HTYPE[a] for a in args) or 'void'))
        o.append('    if (!f) *(void **)&f = hc_sym("%s");' % hname)
        o.append('    if (!f) { hc_missing("%s"); memset(b, 0, 8); return; }' % hname)
        o.append('    int k = 2; (void)k;')
        call, post = [], []; rel = None
        for i, a in enumerate(args):
            v = 'a%d' % i
            if a in ('i', 'L'): o.append('    %s %s = (int)b[k++];' % (HTYPE[a], v))
            elif a in ('u', 'b', 'us', 'UL'): o.append('    %s %s = (%s)b[k++];' % (HTYPE[a], v, HTYPE[a]))
            elif a in ('p', 's', 'pu'): o.append('    %s %s = (%s)P32(b[k++]);' % (HTYPE[a], v, HTYPE[a]))
            elif a == 'h': o.append('    void *%s = hc_handle_get(b[k++]);' % v)
            elif a == 'h!':
                o.append('    u32 %sh = b[k++]; void *%s = hc_handle_get(%sh);' % (v, v, v))
                rel = '%sh' % v
            elif a == 'H': o.append('    u32 %s = b[k++];' % v)
            elif a == 'I': o.append('    void *%s = hc_id_get(b[k++]);' % v)
            elif a == 'pI':
                o.append('    u32 {0}a = b[k++]; void *{0}v = {0}a ? hc_id_get(rd32({0}a)) : 0; void **{0} = {0}a ? &{0}v : 0;'.format(v))
                post.append('    if ({0}a) wr32({0}a, hc_id_put({0}v));'.format(v))
            elif a == 'pC':
                o.append('    u32 {0}k = k; k += 2; CFTypeRef {0}v = 0; CFTypeRef *{0} = &{0}v;'.format(v))
                post.append('    if ({0}v) hc_cf_out({0}v, b + {0}k);'.format(v))
            elif a == 'N': o.append('    void *%s = 0; k++;   /* i386 callback or allocator: not usable here */' % v)
            elif a == 'f': o.append('    float %s; memcpy(&%s, &b[k++], 4);' % (v, v))
            elif a == 'g': o.append('    CGFloat %s = hc_f32(b[k++]);' % v)
            elif a in ('q', 'd'): o.append('    %s %s; memcpy(&%s, &b[k], 8); k += 2;' % (HTYPE[a], v, v))
            elif a == 'R': o.append('    CGRect %s = CGRectMake(hc_f32(b[k]), hc_f32(b[k+1]), hc_f32(b[k+2]), hc_f32(b[k+3])); k += 4;' % v)
            elif a == 'P': o.append('    CGPoint %s = CGPointMake(hc_f32(b[k]), hc_f32(b[k+1])); k += 2;' % v)
            elif a == 'S': o.append('    CGSize %s = CGSizeMake(hc_f32(b[k]), hc_f32(b[k+1])); k += 2;' % v)
            elif a == 'A': o.append('    CGAffineTransform %s = CGAffineTransformMake(hc_f32(b[k]), hc_f32(b[k+1]), hc_f32(b[k+2]), hc_f32(b[k+3]), hc_f32(b[k+4]), hc_f32(b[k+5])); k += 6;' % v)
            elif a == 'c':
                o.append('    CFTypeRef %s = hc_cf_in(b[k], b[k+1]); k += 2;' % v)
                post.append('    if (%s) CFRelease(%s);' % (v, v))
            elif a == 'pg':
                o.append('    u32 {0}a = b[k++]; CGFloat {0}v = {0}a ? hc_f32(rd32({0}a)) : 0; CGFloat *{0} = {0}a ? &{0}v : 0;'.format(v))
                post.append('    if ({0}a) {{ float t = (float){0}v; memcpy(P32({0}a), &t, 4); }}'.format(v))
            elif a == 'pP':
                o.append('    u32 {0}a = b[k++]; CGPoint {0}v = {0}a ? CGPointMake(hc_f32(rd32({0}a)), hc_f32(rd32({0}a + 4))) : CGPointZero; CGPoint *{0} = {0}a ? &{0}v : 0;'.format(v))
                post.append('    if ({0}a) hc_put_pt({0}a, {0}v);'.format(v))
            elif a == 'pR':
                o.append('    u32 {0}a = b[k++]; CGRect {0}v = {0}a ? hc_get_rect({0}a) : CGRectZero; CGRect *{0} = {0}a ? &{0}v : 0;'.format(v))
                post.append('    if ({0}a) hc_put_rect({0}a, {0}v);'.format(v))
            elif a == 'pH':
                o.append('    u32 {0}a = b[k++]; void *{0}v = 0; void **{0} = {0}a ? &{0}v : 0;'.format(v))
                post.append('    if ({0}a) wr32({0}a, hc_handle_put({0}v));'.format(v))
            elif a == 'pUL':
                o.append('    u32 {0}a = b[k++]; unsigned long {0}v = {0}a ? rd32({0}a) : 0; unsigned long *{0} = {0}a ? &{0}v : 0;'.format(v))
                post.append('    if ({0}a) wr32({0}a, (u32){0}v);'.format(v))
            call.append(v)
        if rel: o.append('    if (hc_handle_unref(%s) > 0) { memset(b, 0, 8); return; }   /* still referenced */' % rel)
        c = 'f(%s)' % ', '.join(call)
        if ret == 'v': o.append('    %s;' % c)
        elif ret in ('i', 'u', 'b', 'us', 'L', 'UL'): o.append('    b[0] = (u32)%s;' % c)
        elif ret in ('q', 'd'): o.append('    %s r = %s; memcpy(b, &r, 8);' % (HTYPE[ret], c))
        elif ret == 'g': o.append('    float r = (float)%s; memcpy(b, &r, 4);' % c)
        elif ret == 'h': o.append('    b[0] = hc_handle_put(%s);' % c)
        elif ret == 'C': o.append('    hc_cf_out(%s, b);' % c)
        elif ret == 'W': o.append('    hc_ids_out(%s, b);' % c)
        elif ret == 'P': o.append('    CGPoint r = %s; float t[2] = { (float)r.x, (float)r.y }; memcpy(b + 2, t, 8);' % c)
        elif ret == 'S': o.append('    CGSize r = %s; float t[2] = { (float)r.width, (float)r.height }; memcpy(b + 2, t, 8);' % c)
        elif ret == 'R': o.append('    CGRect r = %s; float t[4] = { (float)r.origin.x, (float)r.origin.y, (float)r.size.width, (float)r.size.height }; memcpy(b + 2, t, 16);' % c)
        o.extend(post)
        o.append('}')
        o.append('')
    o.append('const hc_entry_t g_hc_table[] = {')
    for name, ret, args in fns: o.append('    { "%s", hc_%s },' % (name.split('=')[0], name.split('=')[0]))
    o.append('};')
    o.append('const int g_hc_count = %d;' % len(fns))
    open(path, 'w').write('\n'.join(o) + '\n')

fns = parse(sys.argv[1])
gen_i386(fns, os.path.join(sys.argv[2], 'r2native_gen.c'))
gen_host(fns, os.path.join(sys.argv[2], 'hostcall_gen.c'))
print('%d functions' % len(fns))
