#!/usr/bin/python
# genglspec.py GL_H GLEXT_H > r2gl.spec: hostcall spec lines for the OpenGL functions of the 10.6 SDK
# headers (the i386 OpenGL of the root cannot drive this Mac's GPU: its drivers talk to the Mojave
# kernel). Appended to r2native.spec by build_i386.sh / the host build. Functions this Mac's OpenGL
# lacks are reported missing at the first call (hc_missing) and return 0.
import re, sys

T = {'GLenum': 'u', 'GLbitfield': 'u', 'GLuint': 'u', 'GLint': 'i', 'GLsizei': 'i',
     'GLboolean': 'u', 'GLbyte': 'i', 'GLubyte': 'u', 'GLshort': 'i', 'GLushort': 'u', 'GLchar': 'i',
     'GLcharARB': 'i', 'GLfloat': 'f', 'GLclampf': 'f', 'GLdouble': 'd', 'GLclampd': 'd',
     'GLintptr': 'L', 'GLsizeiptr': 'L', 'GLintptrARB': 'L', 'GLsizeiptrARB': 'L',
     'GLhandleARB': 'u', 'GLint64EXT': 'q', 'GLuint64EXT': 'q', 'GLint64': 'q', 'GLuint64': 'q',
     'GLhalfARB': 'u', 'GLhalfNV': 'u'}
RET = {'void': 'v', 'GLvoid': 'v', 'GLenum': 'u', 'GLuint': 'u', 'GLint': 'i', 'GLboolean': 'u',
       'GLhandleARB': 'u', 'GLbitfield': 'u', 'GLsizei': 'i'}
CUSTOM = set(['glGetString', 'glMapBuffer', 'glMapBufferARB', 'glGetStringi', 'glMapBufferRange',
              'glUnmapBuffer', 'glUnmapBufferARB'])   # r2h_* helpers (r2native.spec)

def argtype(a):
    a = a.strip()
    if a in ('void', 'GLvoid', ''): return None
    if '*' in a or '[' in a: return 'p'
    a = re.sub(r'\bconst\b', '', a).split()
    if not a: return None
    t = a[0]
    if t not in T: raise KeyError(t)
    return T[t]

seen, out, skipped = set(), [], []
for hdr in sys.argv[1:]:
    src = open(hdr).read()
    src = re.compile(r'/\*.*?\*/', re.S).sub('', src)
    for m in re.finditer(r'extern\s+([\w\s\*]+?)\s*\b(gl\w+)\s*\(([^)]*)\)\s*;', src):
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
        if name in seen: continue
        seen.add(name)
        if name in CUSTOM: continue
        try:
            r = 'p' if '*' in ret else RET[re.sub(r'\bconst\b', '', ret).strip()]
            if r == 'p': raise KeyError(ret)
            ts = [t for t in (argtype(x) for x in args.split(',')) if t]
        except KeyError as e:
            skipped.append('%s (%s)' % (name, e)); continue
        out.append('%-40s %s  %s' % (name, r, ' '.join(ts) or '-'))
print('# ---- OpenGL (generated by genglspec.py from the 10.6 SDK headers: %d functions)' % len(out))
print('\n'.join(out))
sys.stderr.write('%d functions, skipped: %s\n' % (len(out), ', '.join(skipped)))
